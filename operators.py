#Arithmetic Operators - Simple Calculations
x = 10
y = 5

print(x+y)
print(x*y)
print(x-y)
print(x/y)
print(x%y)
print(x//y)
print(x**y)

# Comparison Operators - Compare Values
num1 = 50
num2 = 67

print(num1 < num2)
print(num1 > num2)
print(num1 <= num2)
print(num1 >= num2)
print(num1 == num2)
print(num1 != num2)

#Assignment Operators - Assign/Store values in variables
number = 10
print(number)
number += 10 # Addition Assignment
print(number)
number -=10 # Subtraction Assignment
print(number)

# Logical Operators - and, or, not
print(not True) #Not
print(100 == 30 and 60 < 100) #And
print(100 == 30 or 60 < 100) #Or
print(not(100 == 30 or 60 < 100)) #Not




